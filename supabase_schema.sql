-- Design notes / corrections over the draft blueprint:
--   * Audit ledger is a CHAINED hash (prev_hash -> payload_hash), which is the
--     genuinely tamper-evident / patentable property. A plain per-row SHA-256
--     is NOT tamper-evident (a row can be rewritten and re-hashed silently).
--   * system_audit_ledger.target_user_id has NO foreign key and NO CASCADE, so
--     audit rows SURVIVE deletion of a taxpayer (an audit trail that can vanish
--     with its subject is worthless).
--   * RLS is real: citizens can only read their OWN taxpayer row; the audit
--     ledger and notices are readable only by the service_role (the Flask
--     backend). There are no blanket `USING (true)` policies for `authenticated`.
--   * PII identity fields are Fernet-encrypted at the application tier. Numeric
--     income/tax fields stay plaintext so administrative aggregates still work.
--   * pan_blind_index is an HMAC-SHA256 blind search index (Fernet ciphertext
--     is non-deterministic, so you cannot search on the encrypted PAN directly).
-- ============================================================================

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- Clean up previous prototype layers if they exist
DROP TABLE IF EXISTS compliance_notices CASCADE;
DROP TABLE IF EXISTS system_audit_ledger CASCADE;
DROP TABLE IF EXISTS taxpayers CASCADE;

-- 1. Taxpayer registry (application ingests encrypted PII fields)
CREATE TABLE taxpayers (
    user_id              TEXT PRIMARY KEY DEFAULT (gen_random_uuid())::text,
    name_encrypted       TEXT NOT NULL,                    -- base64 Fernet token
    pan_encrypted        TEXT,                             -- base64 Fernet token
    pan_blind_index      CHAR(64),                         -- HMAC-SHA256(pepper, PAN)
    assets_value_encrypted TEXT,                           -- base64 Fernet token
    gross_income         NUMERIC(15, 2) NOT NULL DEFAULT 0, -- plaintext (aggregations)
    declared_deductions  NUMERIC(15, 2) NOT NULL DEFAULT 0,
    tax_paid_to_date     NUMERIC(15, 2) NOT NULL DEFAULT 0,
    expected_tax         NUMERIC(15, 2) NOT NULL DEFAULT 0,
    calculated_risk_score INT NOT NULL DEFAULT 0,          -- 0..100 anomaly index
    recommended_regime   TEXT CHECK (recommended_regime IN ('NEW', 'OLD', 'EQUAL')) DEFAULT 'NEW',
    compliance_status    TEXT CHECK (compliance_status IN ('COMPLIANT','UNDERPAID','FLAGGED_FOR_REVIEW'))
                         NOT NULL DEFAULT 'COMPLIANT',
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX taxpayers_pan_blind_index_idx ON taxpayers (pan_blind_index);

-- 2. Cryptographic audit log (CHAINED, tamper-evident ledger)
CREATE TABLE system_audit_ledger (
    log_id        BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    timestamp     TIMESTAMPTZ NOT NULL,       -- set by the app so it can be included in the hash
    actor_id      TEXT NOT NULL,
    action_type   TEXT NOT NULL,               -- e.g. 'NOTICE_SENT', 'PAYMENT_RECORDED'
    target_user_id TEXT,                       -- NO FK / NO CASCADE on purpose
    payload_json  TEXT NOT NULL,               -- canonical JSON of the event payload
    prev_hash     CHAR(64) NOT NULL,           -- payload_hash of previous row (genesis = 64x'0')
    payload_hash  CHAR(64) NOT NULL            -- SHA256(prev_hash || timestamp || action || actor || target || payload_json)
);
-- NOTE: log_id is deliberately EXCLUDED from the hash input because it is
-- generated by the database identity sequence and is unknown to the app at
-- hashing time. Chain position is already bound uniquely via prev_hash.

-- Append-only enforcement at the database tier: block UPDATE/DELETE of ledger rows.
CREATE OR REPLACE FUNCTION audit_ledger_is_append_only() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'system_audit_ledger is append-only; % is forbidden', TG_OP;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS no_update_audit_ledger ON system_audit_ledger;
CREATE TRIGGER no_update_audit_ledger BEFORE UPDATE ON system_audit_ledger
    FOR EACH ROW EXECUTE FUNCTION audit_ledger_is_append_only();

DROP TRIGGER IF EXISTS no_delete_audit_ledger ON system_audit_ledger;
CREATE TRIGGER no_delete_audit_ledger BEFORE DELETE ON system_audit_ledger
    FOR EACH ROW EXECUTE FUNCTION audit_ledger_is_append_only();

-- 3. Compliance action registry
CREATE TABLE compliance_notices (
    notice_id         BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id           TEXT REFERENCES taxpayers(user_id) ON DELETE CASCADE,
    notice_type       TEXT CHECK (notice_type IN ('REMINDER','WARNING','FINAL','PENALTY','OPTIMIZATION_ADVISORY')) NOT NULL,
    amount_due        NUMERIC(15, 2) NOT NULL DEFAULT 0,
    generated_content TEXT NOT NULL,
    dispatched_status TEXT CHECK (dispatched_status IN ('PENDING','SENT','FAILED')) NOT NULL DEFAULT 'PENDING',
    sent_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================================
-- Row Level Security
-- ============================================================================
ALTER TABLE taxpayers           ENABLE ROW LEVEL SECURITY;
ALTER TABLE system_audit_ledger ENABLE ROW LEVEL SECURITY;
ALTER TABLE compliance_notices  ENABLE ROW LEVEL SECURITY;

-- Citizens: read only their OWN taxpayer row (keyed by Supabase auth uid == user_id).
CREATE POLICY citizens_select_own_taxpayer ON taxpayers
    FOR SELECT TO authenticated
    USING ((auth.uid())::text = user_id);

-- Citizens: read only their OWN notices.
CREATE POLICY citizens_select_own_notices ON compliance_notices
    FOR SELECT TO authenticated
    USING ((auth.uid())::text = user_id);

-- Admin role (JWT claim role='admin') may read/manage all taxpayers.
CREATE POLICY admin_all_taxpayers ON taxpayers
    FOR ALL TO authenticated
    USING (coalesce((auth.jwt() -> 'app_metadata' ->> 'role'), '') = 'admin')
    WITH CHECK (coalesce((auth.jwt() -> 'app_metadata' ->> 'role'), '') = 'admin');

